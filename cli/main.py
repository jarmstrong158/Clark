def _sample_volume_for_date(config, target_date: date) -> tuple[int, str]:
    """
    Sample a realistic order volume for a specific date using the config's
    seasonal_ranges and weekly_curve.

    Returns (volume, label) where label is "Normal Day", "High Volume Day", etc.
    """
    month_name = calendar.month_name[target_date.month]
    dow = target_date.weekday()  # 0=Monday, 4=Friday

    dow_name_map = {
        0: "monday", 1: "tuesday", 2: "wednesday",
        3: "thursday", 4: "friday",
    }

    # Get seasonal base range
    ranges = config.volume.seasonal_ranges
    vol_range = None
    if month_name in ranges:
        vol_range = tuple(ranges[month_name])
    else:
        for k, v in ranges.items():
            if k.lower() == month_name.lower():
                vol_range = tuple(v)
                break
    if vol_range is None:
        vol_range = (100, 300)

    vol_lo, vol_hi = vol_range
    vol_spread = vol_hi - vol_lo

    # Apply weekly curve
    curve = config.volume.weekly_curve
    dow_name = dow_name_map.get(dow, "monday")
    if dow_name in curve:
        pct_lo, pct_hi = curve[dow_name]
    else:
        pct_lo, pct_hi = 0.5, 1.0

    day_vol_lo = vol_lo + int(vol_spread * pct_lo)
    day_vol_hi = vol_lo + int(vol_spread * pct_hi)
    volume = random.randint(day_vol_lo, max(day_vol_lo, day_vol_hi))

    # Label
    high_threshold = config.rules.high_volume_day_orders
    if volume >= high_threshold:
        label = "High Volume Day"
    elif volume >= high_threshold * 0.6:
        label = "Moderate Volume Day"
    else:
        label = "Normal Day"

    return volume, label


def _run_one_plan_day(config, agent, target_date: date, volume: int) -> list[tuple]:
    """
    Simulate the opening assignment for a single day by running the first agent
    step. Returns list of (worker_name, task_name, hustle).
    """
    from clark.env.year_env import YearEnv
    from clark.agent.state import StateBuilder
    from clark.agent.actions import get_action_mask

    env = YearEnv(config)
    builder = StateBuilder(config)

    dow = target_date.weekday()
    month = target_date.month

    env.reset()
    # Re-initialize the inner day_env for this specific date/volume
    env.day_env.reset(
        force_month=month,
        force_dow=dow,
        force_volume=volume,
    )

    agent.reset_hidden()

    state_dict = builder.build(env.day_env)
    mask = get_action_mask(env.day_env)
    task_actions, hustle_actions, _log_prob, _value = agent.select_action_from_dict(state_dict, mask)

    assignments = []
    for i, worker in enumerate(config.workers):
        task_idx = task_actions[i]
        task_name = config.task_ids[task_idx] if task_idx < len(config.task_ids) else "unknown"
        hustle = bool(hustle_actions[i])
        assignments.append((worker.name, task_name, hustle))

    return assignments


def cmd_plan(args: argparse.Namespace):
    _header()

    config_path = Path(args.config)
    model_path = Path(args.model)

    if not config_path.exists():
        _die(f"Config not found: {config_path}")
    if not model_path.exists():
        _die(f"Model checkpoint not found: {model_path}")

    # Parse date
    try:
        if args.date:
            start_date = date.fromisoformat(args.date)
        else:
            start_date = date.today()
    except ValueError:
        _die(f"Invalid date format: {args.date!r}. Use YYYY-MM-DD.")

    try:
        from clark.config.schema import FacilityConfig
        config = FacilityConfig.from_yaml(config_path)
    except Exception as e:
        _die(f"Failed to load config: {e}")

    try:
        from clark.agent.ppo import ClarkAgent
        agent = ClarkAgent.load(str(model_path))
    except Exception as e:
        _die(f"Failed to load model: {e}")

    days_ahead = max(1, args.days)

    for day_offset in range(days_ahead):
        target_date = start_date + timedelta(days=day_offset)

        # Skip weekends
        if target_date.weekday() >= 5:
            continue

        volume, vol_label = _sample_volume_for_date(config, target_date)
        day_name = calendar.day_name[target_date.weekday()]
        date_str = target_date.strftime("%Y-%m-%d")

        try:
            assignments = _run_one_plan_day(config, agent, target_date, volume)
        except Exception as e:
            _die(f"Failed to generate plan for {date_str}: {e}")

        if _RICH:
            title = f"Shift Plan: {day_name} {date_str}"
            border_len = max(len(title) + 4, 46)
            top_border = "╔" + "═" * (border_len - 2) + "╗"
            bot_border = "╚" + "═" * (border_len - 2) + "╝"

            console.print(f"\n[bold cyan]{top_border}[/bold cyan]")
            console.print(f"[bold cyan]║[/bold cyan] [bold]{title}[/bold]")
            console.print(f"[bold cyan]║[/bold cyan] Forecast: ~{volume} orders ([italic]{vol_label}[/italic])")
            console.print(f"[bold cyan]║[/bold cyan]")

            table = Table(show_header=True, header_style="bold", box=None,
                          padding=(0, 1), show_edge=False)
            table.add_column("Worker", min_width=14)
            table.add_column("Task", min_width=16)
            table.add_column("Hustle", min_width=6)

            for worker_name, task_name, hustle in assignments:
                hustle_str = "[green]Yes[/green]" if hustle else "No"
                table.add_row(worker_name, task_name.replace("_", " ").title(), hustle_str)

            console.print(table)
            console.print(f"[bold cyan]{bot_border}[/bold cyan]")
        else:
            title = f"Shift Plan: {day_name} {date_str}"
            border_len = max(len(title) + 4, 46)
            top_border = "╔" + "═" * (border_len - 2) + "╗"
            bot_border = "╚" + "═" * (border_len - 2) + "╝"

            print(f"\n{top_border}")
            print(f"║ {title}")
            print(f"║ Forecast: ~{volume} orders ({vol_label})")
            print(f"║")
            print(f"║ {'Worker':<14} | {'Task':<16} | Hustle")
            print(f"║ {'-'*14}-+-{'-'*16}-+-------")
            for worker_name, task_name, hustle in assignments:
                task_display = task_name.replace("_", " ").title()
                hustle_str = "Yes" if hustle else "No"
                print(f"║ {worker_name:<14} | {task_display:<16} | {hustle_str}")
            print(f"{bot_border}")


def cmd_dashboard(args: argparse.Namespace):
    _header()

    log_dir = Path(args.log_dir).resolve()
    port = args.port
    dashboard_html = Path(__file__).parent.parent / "clark" / "dashboard" / "dashboard.html"

    if not dashboard_html.exists():
        _die(f"Dashboard HTML not found at {dashboard_html}")

    if not log_dir.exists():
        _warn(f"Log directory does not exist yet: {log_dir}")
        _warn("Dashboard will show no data until training produces logs.")

    import http.server
    import threading
    import webbrowser

    dashboard_bytes = dashboard_html.read_bytes()

    class DashboardHandler(http.server.BaseHTTPRequestHandler):
        def log_message(self, fmt, *a):
            pass  # suppress default access log spam

        def do_GET(self):
            from urllib.parse import urlparse
            path = urlparse(self.path).path

            if path in ("/", "/index.html"):
                self._send(200, "text/html; charset=utf-8", dashboard_bytes)
            elif path in ("/data/year_snapshot.json", "/clark/data/year_snapshot.json",
                          "/volt_sim/data/year_snapshot.json"):
                self._serve_json("year_snapshot.json")
            elif path == "/data/episode_log.json":
                self._serve_json("episode_log.json")
            else:
                self._send(404, "text/plain", b"Not found")

        def _serve_json(self, filename: str):
            fpath = log_dir / filename
            if fpath.exists():
                try:
                    data = fpath.read_bytes()
                    self._send(200, "application/json", data)
                except Exception:
                    self._send(500, "text/plain", b"Error reading file")
            else:
                # Return empty valid structure so dashboard doesn't error out
                self._send(200, "application/json",
                           b'{"episodes":[],"training_stats":{},"year_summary":{}}')

        def _send(self, code: int, ctype: str, body: bytes):
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(body)

    server = http.server.HTTPServer(("localhost", port), DashboardHandler)

    url = f"http://localhost:{port}"
    print(f"  Dashboard: {url}")
    print(f"  Log dir:   {log_dir}")
    print(f"  Auto-refreshes every 10s while training is running.")
    print(f"  Press Ctrl+C to stop.\n")

    # Open browser after a short delay
    def _open():
        import time
        time.sleep(0.5)
        webbrowser.open(url)
    threading.Thread(target=_open, daemon=True).start()

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nDashboard stopped.")


# ── Argument parser ───────────────────────────────────────────────────────────

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="clark",
        description=HEADER,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", metavar="COMMAND")
    sub.required = True

    # init
    p_init = sub.add_parser("init", help="Scaffold a new facility config YAML.")
    p_init.add_argument("output_path", metavar="OUTPUT_PATH",
                        help="Path to write the new YAML config.")

    # validate
    p_val = sub.add_parser("validate", help="Load and validate a facility config.")
    p_val.add_argument("config_path", metavar="CONFIG_PATH",
                       help="Path to the facility YAML config.")

    # pretrain
    p_pre = sub.add_parser("pretrain", help="Pre-train the Clark foundation model.")
    p_pre.add_argument("--episodes", type=int, default=10000,
                       help="Number of training episodes (default: 10000).")
    p_pre.add_argument("--output", type=str,
                       default="clark/data/checkpoints/clark_foundation.pt",
                       help="Output checkpoint path.")
    p_pre.add_argument("--log-interval", type=int, default=10,
                       help="Print progress every N episodes (default: 10).")
    p_pre.add_argument("--save-interval", type=int, default=100,
                       help="Save checkpoint every N episodes (default: 100).")

    # finetune
    p_ft = sub.add_parser("finetune", help="Fine-tune from a foundation checkpoint.")
    p_ft.add_argument("--config", required=True,
                      help="Path to facility YAML config.")
    p_ft.add_argument("--base", required=True,
                      help="Path to the foundation checkpoint (.pt).")
    p_ft.add_argument("--output", default="clark/data/checkpoints/finetuned.pt",
                      help="Output path for fine-tuned checkpoint.")
    p_ft.add_argument("--episodes", type=int, default=500,
                      help="Number of fine-tuning episodes (default: 500).")
    p_ft.add_argument("--lr", type=float, default=5e-5,
                      help="Learning rate (default: 5e-5).")
    p_ft.add_argument("--freeze-encoder", action="store_true",
                      help="Freeze encoder layers (prevents catastrophic forgetting).")

    # plan
    p_plan = sub.add_parser("plan", help="Generate a shift plan using a trained model.")
    p_plan.add_argument("--config", required=True,
                        help="Path to facility YAML config.")
    p_plan.add_argument("--model", required=True,
                        help="Path to model checkpoint (.pt).")
    p_plan.add_argument("--date", default=None,
                        help="Start date in YYYY-MM-DD format (default: today).")
    p_plan.add_argument("--days", type=int, default=1,
                        help="Number of days to plan ahead (default: 1).")

    # dashboard
    p_dash = sub.add_parser("dashboard", help="Launch the Clark training dashboard.")
    p_dash.add_argument("--log-dir", default="clark/data/logs/pretrain",
                        help="Directory containing episode_log.json / year_snapshot.json.")
    p_dash.add_argument("--port", type=int, default=8080,
                        help="Port to serve the dashboard on (default: 8080).")

    return parser


# ── Entry point ───────────────────────────────────────────────────────────────

def main():
    parser = build_parser()
    args = parser.parse_args()

    dispatch = {
        "init":      cmd_init,
        "validate":  cmd_validate,
        "pretrain":  cmd_pretrain,
        "finetune":  cmd_finetune,
        "plan":      cmd_plan,
        "dashboard": cmd_dashboard,
    }

    fn = dispatch.get(args.command)
    if fn is None:
        parser.print_help()
        sys.exit(1)

    fn(args)


# Allow direct invocation: python cli/main.py <command>
app = main  # pyproject.toml entry point: clark = "cli.main:app"

if __name__ == "__main__":
    main()
