def _ok(msg: str):
    if _RICH:
        console.print(f"[bold green]{msg}[/bold green]")
    else:
        print(msg)


def _warn(msg: str):
    if _RICH:
        console.print(f"[bold yellow]  Warning: {msg}[/bold yellow]")
    else:
        print(f"  Warning: {msg}")


def _err(msg: str):
    if _RICH:
        console.print(f"[bold red]  Error: {msg}[/bold red]")
    else:
        print(f"  Error: {msg}", file=sys.stderr)


def _die(msg: str):
    _err(msg)
    sys.exit(1)


# ── Template content ──────────────────────────────────────────────────────────

def _load_template(template: str, name: str) -> str:
    """Return template YAML text with a header comment and the facility name substituted."""
    clark_root = Path(__file__).parent.parent
    template_map = {
        "small": clark_root / "clark" / "data" / "configs" / "example_small.yaml",
        "large": clark_root / "clark" / "data" / "configs" / "example_large.yaml",
        "volt":  clark_root / "clark" / "data" / "configs" / "volt_warehouse.yaml",
    }
    path = template_map.get(template)
    if path is None or not path.exists():
        _die(f"Template '{template}' not found at {path}.")

    text = path.read_text(encoding="utf-8")

    # Swap facility name into the first occurrence of the name field
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("name:"):
            old_line = line
            new_line = line.split("name:")[0] + f'name: "{name}"'
            text = text.replace(old_line, new_line, 1)
            break

    header_comment = "# Generated by 'clark init' — fill in your real values\n"
    return header_comment + text


# ── Commands ──────────────────────────────────────────────────────────────────

def cmd_init(args: argparse.Namespace):
    _header()
    output_path = Path(args.output_path)

    print("Scaffolding a new facility config...\n")

    # Prompt: facility name
    try:
        name = input("Facility name: ").strip()
        if not name:
            name = "My Warehouse"
    except (EOFError, KeyboardInterrupt):
        name = "My Warehouse"

    # Prompt: number of workers (informational)
    try:
        input("Approximate number of workers: ").strip()
    except (EOFError, KeyboardInterrupt, ValueError):
        pass

    # Prompt: template
    try:
        tmpl_input = input("Start from template? [small/large/volt] (default: small): ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        tmpl_input = ""

    tmpl = tmpl_input if tmpl_input in ("small", "large", "volt") else "small"

    content = _load_template(tmpl, name)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")

    _ok(f"Config written to: {output_path}")
    print(f"Template: {tmpl}")
    print("Edit the file to match your facility's real values, then run:")
    print(f"  clark validate {output_path}")


def cmd_validate(args: argparse.Namespace):
    _header()
    config_path = Path(args.config_path)

    if not config_path.exists():
        _die(f"Config file not found: {config_path}")

    try:
        from clark.config.schema import FacilityConfig
        config = FacilityConfig.from_yaml(config_path)
    except Exception as e:
        _die(f"Failed to load config: {e}")

    errors, warnings = config.validate()

    # Volume summary: find overall min/max across all months
    all_lows = [v[0] for v in config.volume.seasonal_ranges.values()]
    all_highs = [v[1] for v in config.volume.seasonal_ranges.values()]
    vol_lo = min(all_lows) if all_lows else 0
    vol_hi = max(all_highs) if all_highs else 0

    print(f"  Name:         {config.name}")
    print(f"  Workers:      {config.num_workers}")
    print(f"  Tasks:        {config.num_tasks}  ({', '.join(config.task_ids)})")
    print(f"  Volume range: {vol_lo}–{vol_hi} orders/day")
    print()

    if errors:
        for e in errors:
            _err(e)
        print()
    if warnings:
        for w in warnings:
            _warn(w)
        print()

    if errors:
        _err(f"Config has {len(errors)} blocking error(s). Fix before training.")
        sys.exit(1)
    else:
        _ok("Config is valid!")


